import fs from 'node:fs';

const root = new URL('../native-skills/', import.meta.url);
const skills = {};
const forbidden = new Set(['agent-docs', 'agent_docs', 'doctrine', 'internal']);

function formatStringLiteral(str, indent = 8, maxLine = 75) {
  if (typeof str !== 'string') return JSON.stringify(str);
  if (str.length <= maxLine && !str.includes('\n')) {
    return JSON.stringify(str);
  }
  const pad = ' '.repeat(indent);
  const rawLines = str.split('\n');
  const items = [];
  for (let i = 0; i < rawLines.length; i++) {
    const rawLine = rawLines[i] + (i < rawLines.length - 1 ? '\n' : '');
    if (rawLine.length === 0) continue;
    if (rawLine.length <= maxLine) {
      items.push(pad + JSON.stringify(rawLine));
    } else {
      for (let c = 0; c < rawLine.length; c += maxLine) {
        items.push(pad + JSON.stringify(rawLine.slice(c, c + maxLine)));
      }
    }
  }
  if (items.length === 0) return '""';
  return '[\n' + items.join(',\n') + '\n' + ' '.repeat(indent - 2) + '].join(\'\')';
}

for (const domain of fs.readdirSync(root, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
  if (!domain.isDirectory() || domain.name.startsWith('.')) continue;
  if (forbidden.has(domain.name)) throw new Error(`Developer instructions are not product skills: ${domain.name}`);
  skills[domain.name] = {};
  const domainUrl = new URL(`${domain.name}/`, root);
  for (const entry of fs.readdirSync(domainUrl, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isDirectory() || entry.name.startsWith('.')) continue;
    const file = new URL(`${entry.name}/SKILL.md`, domainUrl);
    if (!fs.existsSync(file)) continue;
    // Git may check Markdown out with CRLF on Windows. Normalize before both
    // parsing and embedding so the generated module is byte-identical on every
    // supported runner and release artifacts do not depend on checkout policy.
    const content = fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n');
    const frontmatter = content.match(/^---\n([\s\S]*?)\n---/)?.[1] || '';
    const name = frontmatter.match(/^name:\s*(.+)$/m)?.[1]?.trim() || entry.name;
    const description = frontmatter.match(/^description:\s*(.+)$/m)?.[1]?.trim() || '';
    skills[domain.name][name] = { name, description, content };
  }
}

let code = '// Generated by scripts/compile_skills.js. Human-readable product skills.\n';
code += '// Formatted to adhere strictly to line-length and transparency standards.\n';
code += 'export const COMPILED_SKILLS = {\n';

const domainKeys = Object.keys(skills).sort();
for (let d = 0; d < domainKeys.length; d++) {
  const domain = domainKeys[d];
  code += `  ${JSON.stringify(domain)}: {\n`;
  const skillKeys = Object.keys(skills[domain]).sort();
  for (let s = 0; s < skillKeys.length; s++) {
    const skillName = skillKeys[s];
    const skill = skills[domain][skillName];
    code += `    ${JSON.stringify(skillName)}: {\n`;
    code += `      name: ${JSON.stringify(skill.name)},\n`;
    code += `      description: ${formatStringLiteral(skill.description, 8, 75)},\n`;
    code += `      content: ${formatStringLiteral(skill.content, 8, 75)}\n`;
    code += `    }${s < skillKeys.length - 1 ? ',' : ''}\n`;
  }
  code += `  }${d < domainKeys.length - 1 ? ',' : ''}\n`;
}
code += '};\n';

fs.writeFileSync(new URL('../src/compiledSkills.js', import.meta.url), code, 'utf8');
console.log(`Generated ${Object.values(skills).reduce((n, domain) => n + Object.keys(domain).length, 0)} readable skills.`);
