    '  async function submitPrompt(promptText, attachList) {',
    '    const prompt = (promptText || "").trim();',
    '    if (!prompt || state.activeController) return;',
    '    state.lastPrompt = prompt;',
    '    appendUserTurn(prompt, attachList);',
    '    const assistant = createAssistantTurn(prompt);',
    '    state.activeController = new AbortController();',
    '    updateComposerMetrics();',
    '    announceStatus("Causyne is working...");',
    '',
    '    try {',
    '      const res = await fetch(apiUrl("/api/chat"), {',
    '        method: "POST",',
    '        headers: authHeaders({ "Content-Type": "application/json" }),',
    '        body: JSON.stringify({',
    '          prompt,',
    '          mode: modeSelect.value,',
    '          sessionId: state.sessionId || undefined,',
    '          attachments: attachList',
    '        }),',
    '        signal: state.activeController.signal',
    '      });',
    '      if (!res.ok || !res.body) {',
    '        const errData = await res.json().catch(() => ({ error: "HTTP " + res.status }));',
    '        assistant.addError(errData.error || "Request failed.");',
    '        return;',
    '      }',
    '      const reader = res.body.getReader();',
    '      const decoder = new TextDecoder();',
    '      let buf = "";',
    '      while (true) {',
    '        const step = await reader.read();',
    '        if (step.done) break;',
    '        buf += decoder.decode(step.value, { stream: true });',
    '        const lines = buf.split("\\n");',
    '        buf = lines.pop() || "";',
    '        for (const line of lines) {',
    '          if (!line.trim()) continue;',
    '          let ev = null; try { ev = JSON.parse(line); } catch { continue; }',
    '          if (ev.type === "session_bound" && ev.sessionId) {',
    '            state.sessionId = ev.sessionId;',
    '          } else if (ev.type === "reasoning_chunk" && ev.delta) {',
    '            assistant.appendReasoning(ev.delta);',
    '          } else if (ev.type === "agent_chunk" && ev.delta) {',
    '            assistant.appendText(ev.delta);',
    '          } else if (ev.type === "agent_message" && ev.content) {',
    '            assistant.setText(ev.content);',
    '          } else if (ev.type === "tool_start") {',
    '            assistant.addToolStart(ev);',
    '          } else if (ev.type === "tool_result") {',
    '            assistant.addToolResult(ev);',
    '          } else if (ev.type === "approval_request") {',
    '            assistant.addApproval(ev);',
    '          } else if (ev.type === "notice" && ev.message) {',
    '            assistant.addNotice(ev.message);',
    '          } else if (ev.type === "error") {',
    '            assistant.addError(ev.message || "Task error.");',
    '          }',
    '        }',
    '      }',
    '      assistant.finish();',
    '      announceStatus("Response complete.");',
    '      void loadSessions();',
    '      if (appEl.classList.contains("studio-open")) {',
    '        if (state.studioTab === "files") void loadFiles(state.currentDir, fileFilterEl.value || "");',
    '        if (state.studioTab === "diff") void loadDiff();',
    '      }',
    '    } catch (err) {',
    '      if (err && err.name !== "AbortError") assistant.addError("Connection interrupted.");',
    '      assistant.finish();',
    '    } finally {',
    '      state.activeController = null;',
    '      updateComposerMetrics();',
    '    }',
    '  }',
