export function announceStatus(msg: string): void {
  if (dom.ariaStatusEl) dom.ariaStatusEl.textContent = msg;
}

export function announceAlert(msg: string): void {
  if (dom.ariaAlertEl) dom.ariaAlertEl.textContent = msg;
}

export function copyText(text: string, btn?: HTMLElement | null): void {
  const done = (): void => {
    if (!btn) return;
    const prev = btn.textContent;
    btn.textContent = 'Copied';
    setTimeout(() => { btn.textContent = prev; }, 1400);
  };
  if (navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(text).then(done).catch(() => {});
  }
}

export function cloneCausyneMark(extraClass?: string): SVGSVGElement | null {
  const tpl = document.getElementById('causyne-mark-svg');
  if (!tpl) return null;
  const clone = tpl.cloneNode(true) as SVGSVGElement;
  clone.removeAttribute('id');
  if (extraClass) clone.classList.add(extraClass);
  return clone;
}
