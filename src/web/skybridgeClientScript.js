        '      buf = lines.pop() || "";',
        '      for (const line of lines) {',
        '        if (!line.trim()) continue;',
        '        let ev = null; try { ev = JSON.parse(line); } catch { continue; }',
        '        if (ev.type === "heartbeat") {',
        '          continue;',
        '        } else if (ev.type === "idle") {',
        '          receivedIdle = true;',
