        '              void loadDiff();',
        '            }',
        '          } else {',
        '            assistant.addNotice(ev.message);',
        '          }',
        '        } else if (ev.type === "stopped") {',
        '          receivedTerminal = true;',
        '          assistant.addInterrupted("You stopped Causyne\\u2019s response.", promptForRetry);',
        '        } else if (ev.type === "done") {',
        '          receivedTerminal = true;',
