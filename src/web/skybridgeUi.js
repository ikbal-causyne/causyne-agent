/**
 * Causyne Local Skybridge Web UI
 *
 * Zero-CDN, zero-external-script, strict-CSP browser workspace served directly
 * from the foreground `127.0.0.1` Skybridge server. Uses safe DOM construction
 * (`textContent` / `createElement` — never `innerHTML`) for XSS immunity.
 */
function escapeHtmlAttr(value) {
    return value
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}
