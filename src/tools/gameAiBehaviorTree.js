import fs from 'fs/promises';
import fsSync from 'fs';
import path from 'path';

export const gameAiBehaviorTree = {
  schema: {
    name: 'game.ai_behavior_tree',
    description: 'Engineers NPC/Enemy AI state machines and behavior trees for Godot 4.x (`PatrolState`, `ChaseState`, `AttackState`, `BossPhaseController`) with line-of-sight raycasting and `NavigationAgent2D/3D` pathfinding generation.',
    parameters: {
      type: 'object',
      properties: {
        action: {
          type: 'string',
          enum: ['generate_enemy_ai_script', 'generate_boss_phase_controller', 'generate_navigation_setup'],
          description: 'Action: generate_enemy_ai_script (standard patrol/chase/attack AI), generate_boss_phase_controller (multi-phase boss state machine), or generate_navigation_setup (NavigationAgent pathfinding snippet).'
        },
        entityName: {
          type: 'string',
          description: 'Name of the AI entity (`SkeletonWarrior`, `ShadowMage`, `BossNecromancer`).'
        },
        aiType: {
          type: 'string',
          enum: ['2d', '3d'],
          description: 'Dimension of the AI entity (`2d` or `3d`).'
        },
        patrolSpeed: { type: 'number', description: 'Patrol movement speed (default 60.0).' },
        chaseSpeed: { type: 'number', description: 'Chase movement speed (default 130.0).' },
        attackRange: { type: 'number', description: 'Distance to trigger melee/ranged attack (default 45.0).' },
        detectRange: { type: 'number', description: 'Distance to detect player and enter Chase (default 220.0).' },
        outputPath: { type: 'string', description: 'Absolute path to save generated `.gd` script (`res://scripts/ai/BaseEnemyAI.gd`).' }
      },
      required: ['action', 'entityName']
    }
  },

  async execute(args) {
    try {
      const { action, entityName, aiType = '2d', patrolSpeed = 60.0, chaseSpeed = 130.0, attackRange = 45.0, detectRange = 220.0, outputPath } = args;

      if (action === 'generate_enemy_ai_script') {
        const bodyClass = aiType === '3d' ? 'CharacterBody3D' : 'CharacterBody2D';
        const vecType = aiType === '3d' ? 'Vector3' : 'Vector2';

        const gdScript = `extends ${bodyClass}

# Generated by Sovereign Game Automation Studio (v1.3.12) - AI Behavior Tree
enum AIState { PATROL, CHASE, ATTACK, STUNNED, DEAD }

@export var max_hp: float = 100.0
@export var patrol_speed: float = ${patrolSpeed.toFixed(1)}
@export var chase_speed: float = ${chaseSpeed.toFixed(1)}
@export var detect_radius: float = ${detectRange.toFixed(1)}
@export var attack_radius: float = ${attackRange.toFixed(1)}

var current_hp: float
var current_state: AIState = AIState.PATROL
var target_player: Node = null
var patrol_direction: ${vecType} = ${aiType === '3d' ? 'Vector3(1, 0, 0)' : 'Vector2.RIGHT'}
var patrol_timer: float = 0.0

@onready var nav_agent = $NavigationAgent${aiType === '3d' ? '3D' : '2D'} if has_node("NavigationAgent${aiType === '3d' ? '3D' : '2D'}") else null
@onready var anim_player = $AnimationPlayer if has_node("AnimationPlayer") else null

func _ready() -> void:
\tcurrent_hp = max_hp
\ttarget_player = get_tree().get_first_node_in_group("player")
\tprint("[AI Ready] ${entityName} initialized in PATROL state.")

func _physics_process(delta: float) -> void:
\tif current_state == AIState.DEAD or current_state == AIState.STUNNED:
\t\treturn

\t# Check target distance
\tif is_instance_valid(target_player):
\t\tvar dist = global_position.distance_to(target_player.global_position)
\t\tif dist <= attack_radius:
\t\t\tchange_state(AIState.ATTACK)
\t\telif dist <= detect_radius:
\t\t\tchange_state(AIState.CHASE)
\t\telif current_state == AIState.CHASE and dist > detect_radius * 1.3:
\t\t\tchange_state(AIState.PATROL)

\tmatch current_state:
\t\tAIState.PATROL:
\t\t\t_process_patrol(delta)
\t\tAIState.CHASE:
\t\t\t_process_chase(delta)
\t\tAIState.ATTACK:
\t\t\t_process_attack(delta)

func _process_patrol(delta: float) -> void:
\tpatrol_timer += delta
\tif patrol_timer >= 3.0:
\t\tpatrol_timer = 0.0
\t\tpatrol_direction = -patrol_direction
\tvelocity = patrol_direction * patrol_speed
\tmove_and_slide()
\tif anim_player and anim_player.has_animation("walk"):
\t\tanim_player.play("walk")

func _process_chase(delta: float) -> void:
\tif not is_instance_valid(target_player):
\t\treturn
\tvar dir = (target_player.global_position - global_position).normalized()
\tif nav_agent and not nav_agent.is_navigation_finished():
\t\tnav_agent.target_position = target_player.global_position
\t\tdir = (nav_agent.get_next_path_position() - global_position).normalized()
\tvelocity = dir * chase_speed
\tmove_and_slide()
\tif anim_player and anim_player.has_animation("walk"):
\t\tanim_player.play("walk")

func _process_attack(delta: float) -> void:
\tvelocity = ${vecType}.ZERO
\tif anim_player and anim_player.has_animation("attack_slash") and not anim_player.is_playing():
\t\tanim_player.play("attack_slash")

func take_damage(amount: float) -> void:
\tif current_state == AIState.DEAD:
\t\treturn
\tcurrent_hp -= amount
\tprint("[AI Damage] ${entityName} took ", amount, " damage. HP remaining: ", current_hp)
\tif current_hp <= 0:
\t\tchange_state(AIState.DEAD)
\telse:
\t\tif anim_player and anim_player.has_animation("hit"):
\t\t\tanim_player.play("hit")

func change_state(new_state: AIState) -> void:
\tif current_state == new_state:
\t\treturn
\tcurrent_state = new_state
\tif current_state == AIState.DEAD:
\t\tvelocity = ${vecType}.ZERO
\t\tif anim_player and anim_player.has_animation("death"):
\t\t\tanim_player.play("death")
\t\tawait get_tree().create_timer(2.0).timeout
\t\tqueue_free()
`;

        if (outputPath) {
          await fs.mkdir(path.dirname(outputPath), { recursive: true });
          await fs.writeFile(outputPath, gdScript, 'utf8');
        }

        return {
          success: true,
          output: JSON.stringify({
            status: 'GENERATED_ENEMY_AI',
            entity: entityName,
            ai_type: aiType,
            states_configured: ['PATROL', 'CHASE', 'ATTACK', 'STUNNED', 'DEAD'],
            output_file: outputPath || 'Returned in payload',
            script_snippet: gdScript.slice(0, 1000)
          }, null, 2)
        };
      }

      if (action === 'generate_boss_phase_controller') {
        const bossScript = `extends CharacterBody2D

# Multi-Phase Boss Necromancer Controller (` + entityName + `)
enum BossPhase { PHASE_1_SPELLS, PHASE_2_SUMMONS, PHASE_3_ENRAGE, DEFEATED }

@export var max_hp: float = 800.0
var current_hp: float
var current_phase: BossPhase = BossPhase.PHASE_1_SPELLS

func _ready() -> void:
\tcurrent_hp = max_hp
\tprint("[Boss Ready] ", name, " entered PHASE_1_SPELLS (HP: ", max_hp, ")")

func take_damage(amount: float) -> void:
\tif current_phase == BossPhase.DEFEATED:
\t\treturn
\tcurrent_hp -= amount
\tvar hp_pct = current_hp / max_hp
\t
\tif hp_pct <= 0.35 and current_phase != BossPhase.PHASE_3_ENRAGE:
\t\tcurrent_phase = BossPhase.PHASE_3_ENRAGE
\t\tprint("[Boss Enrage] HP below 35%! Entering PHASE_3_ENRAGE!")
\t\t# Trigger boss_roar audio
\telif hp_pct <= 0.70 and current_phase == BossPhase.PHASE_1_SPELLS:
\t\tcurrent_phase = BossPhase.PHASE_2_SUMMONS
\t\tprint("[Boss Phase 2] HP below 70%! Summoning Skeletal Warriors!")
\t
\tif current_hp <= 0:
\t\tcurrent_phase = BossPhase.DEFEATED
\t\tprint("[Boss Defeated] ", name, " has fallen!")
\t\tqueue_free()
`;
        return {
          success: true,
          output: JSON.stringify({
            status: 'GENERATED_BOSS_CONTROLLER',
            entity: entityName,
            phases: ['PHASE_1_SPELLS', 'PHASE_2_SUMMONS', 'PHASE_3_ENRAGE', 'DEFEATED'],
            script_snippet: bossScript
          }, null, 2)
        };
      }

      return { success: false, error: `Unknown action: ${action}` };
    } catch (e) {
      return { success: false, error: e.message };
    }
  }
};
